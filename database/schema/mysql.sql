  title VARCHAR(255) NOT NULL,
  factor_id BIGINT UNSIGNED NULL,
  priority_area_id BIGINT UNSIGNED NULL,
  recommendation_id BIGINT UNSIGNED NULL,
  issue TEXT NULL,
  description TEXT NULL,
  objective TEXT NULL,
  responsible_department_id BIGINT UNSIGNED NULL,
